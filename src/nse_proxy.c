/* NSE_Protect(fn) -> "true" | "NATIVE_FAULT:0x..." | "LUA_ERROR:..."
 *
 * Runs a Lua function with the crash guard ARMED. Without this, only REPL evals
 * are protected - and mod code lives in event handlers, which the engine calls
 * directly.
 *
 * `pcall` DOES NOT PROTECT YOU. The engine's condition functions are native C
 * that dereference their arguments without validating, so a wrong arity or a
 * wrong-scoped context is a hard access violation, not a catchable Lua error.
 * pcall catches Lua errors only.
 *
 * Wrap anything that touches conditions / effect / game_interface:
 *
 *     scripting.AddEventCallBack("FactionTurnStart", function(context)
 *         NSE_Protect(function() ... end)
 *     end)
 *
 * Its own jmp_buf, because a handler can run while a REPL eval is in flight. */
static volatile LONG g_prot_busy = 0;

static int __cdecl nse_protect(lua_State* L) {
    if (L_.type(L, 1) != LUA_TFUNCTION) {
        push_str(L, "NSE_Protect: expected a function");
        return 1;
    }
    /* No nesting: an inner fault would clobber the outer jmp_buf. Degrade to a
     * plain pcall rather than refusing outright. */
    if (InterlockedCompareExchange(&g_prot_busy, 1, 0) != 0) {
        int rc0 = L_.pcall(L, 0, 0, 0);
        push_str(L, rc0 ? "LUA_ERROR (nested)" : "true");
        return 1;
    }

    if (setjmp(g_prot_jmp) != 0) {          /* arrived here from the VEH */
        char buf[96];
        _snprintf(buf, sizeof(buf)-1, "NATIVE_FAULT:0x%08lX", g_guard_code);
        buf[sizeof(buf)-1] = 0;
        nse_log("[nse] NSE_Protect caught a native fault (0x%08lX)", g_guard_code);
        g_guard_armed = 0;
        InterlockedExchange(&g_prot_busy, 0);
        L_.settop(L, 0);
        push_str(L, buf);
        return 1;
    }

    g_guard_use_prot = 1;
    g_guard_armed    = 1;
    int rc = L_.pcall(L, 0, 0, 0);
    g_guard_armed    = 0;
    g_guard_use_prot = 0;
    InterlockedExchange(&g_prot_busy, 0);

    if (rc != 0) {
        const char* e = L_.tolstring(L, -1, NULL);
        char buf[512];
        _snprintf(buf, sizeof(buf)-1, "LUA_ERROR:%s", e ? e : "?");
        buf[sizeof(buf)-1] = 0;
        L_.settop(L, 0);
        push_str(L, buf);
    } else {
        push_str(L, "true");
    }
    return 1;
}

/* ===================== live memory inspection ============================ *
 * Turns NSE into a debugger for the running game: read the engine's own
 * structures while a campaign is loaded, instead of inferring them from a crash
 * dump afterwards. Napoleon's campaign object graph is undocumented, and this
 * is how you map it.
 *
 * String in, string out. Only tolstring and pushlstring are bound, not
 * tonumber/pushnumber - and lua_Number is a double, awkward to push from here.
 * Lua's own tonumber() handles the conversion on the other side.
 *
 * Every read is bounds-checked with VirtualQuery FIRST. A bad address returns
 * "UNREADABLE" rather than faulting: this exists for poking at unknown
 * structures, so it must never be able to take the game down. */
static int mem_readable(const void* p, size_t n) {
    MEMORY_BASIC_INFORMATION mbi;
    if (!p) return 0;
    if (VirtualQuery(p, &mbi, sizeof(mbi)) == 0) return 0;
    if (mbi.State != MEM_COMMIT) return 0;
    if (mbi.Protect & PAGE_GUARD) return 0;
    DWORD prot = mbi.Protect & 0xFF;
    if (prot == PAGE_NOACCESS || prot == PAGE_EXECUTE) return 0;
    size_t avail = (size_t)(((char*)mbi.BaseAddress + mbi.RegionSize) - (char*)p);
    return avail >= n;
}

/* accepts "0x14A4174", "14A4174" (hex assumed) or "#12345" for decimal */
static DWORD parse_addr(const char* s) {
    if (!s) return 0;
    while (*s == ' ') s++;
    if (*s == '#') return (DWORD)strtoul(s + 1, NULL, 10);
    if (s[0] == '0' && (s[1] == 'x' || s[1] == 'X')) return (DWORD)strtoul(s + 2, NULL, 16);
    return (DWORD)strtoul(s, NULL, 16);
}

/* NSE_Delta() -> "0x3F0000" : add to a static (Ghidra) address for a live one */
static int __cdecl nse_delta(lua_State* L) {
    char b[32]; _snprintf(b, sizeof(b)-1, "0x%lX", (unsigned long)g_delta); b[31]=0;
    push_str(L, b); return 1;
}

static int __cdecl nse_readint(lua_State* L) {
    DWORD a = parse_addr(L_.tolstring(L, 1, NULL));
    if (!mem_readable((void*)a, 4)) { push_str(L, "UNREADABLE"); return 1; }
    char b[32]; _snprintf(b, sizeof(b)-1, "%ld", (long)*(int*)a); b[31]=0;
    push_str(L, b); return 1;
}

static int __cdecl nse_readfloat(lua_State* L) {
    DWORD a = parse_addr(L_.tolstring(L, 1, NULL));
    if (!mem_readable((void*)a, 4)) { push_str(L, "UNREADABLE"); return 1; }
    char b[48]; _snprintf(b, sizeof(b)-1, "%f", (double)*(float*)a); b[47]=0;
    push_str(L, b); return 1;
}

/* NSE_ReadBytes("0x...", "#16") -> "56 8B F9 ..." (max 64) */
static int __cdecl nse_readbytes(lua_State* L) {
    DWORD a = parse_addr(L_.tolstring(L, 1, NULL));
    int   n = (int)parse_addr(L_.tolstring(L, 2, NULL));
    if (n <= 0 || n > 64) n = 16;
    if (!mem_readable((void*)a, (size_t)n)) { push_str(L, "UNREADABLE"); return 1; }
    char b[256]; int w = 0;
    for (int i = 0; i < n && w < (int)sizeof(b)-4; i++)
        w += _snprintf(b+w, sizeof(b)-1-w, "%02X ", ((unsigned char*)a)[i]);
    b[w > 0 ? w-1 : 0] = 0;
    push_str(L, b); return 1;
}

/* NSE_ReadStr("0x...", "#64") -> the C string there, or "UNREADABLE" */
static int __cdecl nse_readstr(lua_State* L) {
    DWORD a = parse_addr(L_.tolstring(L, 1, NULL));
    int   n = (int)parse_addr(L_.tolstring(L, 2, NULL));
    if (n <= 0 || n > 255) n = 64;
    if (!mem_readable((void*)a, 1)) { push_str(L, "UNREADABLE"); return 1; }
    char b[256]; int i = 0;
    for (; i < n; i++) {
        if (!mem_readable((void*)(a+i), 1)) break;
        char c = ((char*)a)[i];
        if (c == 0) break;
        b[i] = (c >= 32 && c < 127) ? c : '.';
    }
    b[i] = 0;
    push_str(L, b); return 1;
}

/* NSE_Log("text") -> writes to nse_log.txt immediately.
 *
 * The point is CRASH SURVIVAL: nse_log opens, writes and closes per line, so
 * anything logged is on disk before the next statement runs. That makes it the
 * only reliable way to get data out of a session that is about to die - the
 * pipe cannot help, because you cannot hand-time a request into the window
 * between campaign-script init and a fault. */
static int __cdecl nse_luaLog(lua_State* L) {
    const char* s = L_.tolstring(L, 1, NULL);
    nse_log("[lua] %s", s ? s : "(nil)");
    push_str(L, "ok");
    return 1;
}

/* ===================== NSE_Say: campaign -> UI bridge =====================
 * Lets a MOD talk to the player on its own, rather than only when a human runs
 * nse.ps1 -Say.
 *
 * The problem it solves: mod code runs in the CAMPAIGN lua_State, but
 * panelmanager - the only way to put text on screen - exists solely in the UI
 * state. They are separate lua_States and neither can call the other.
 *
 * Same queue-and-pump shape as the pipe: NSE_Say() stores the text, and the
 * next time a Lua hook fires we evaluate the panel call IN THE UI STATE.
 * Nothing crosses a thread boundary (both states live on the game thread).
 *
 * Napoleon's own UI does exactly this. Extracted from data.pack:
 *   ui\common ui\dialogue_box.luac  requires 'Utilities'.Require('PanelManager')
 *                                   and exposes Initialise(txt, ok_cb, cancel_cb)
 *   ui\panelmanager.luac            requires 'CoreUtils', exposes OpenPanel,
 *                                   IsPanelOpen, ClosePanel, and knows
 *                                   'dialogue_box'
 * Both module spellings are tried, because the two shipped scripts disagree.
 */
#define SAY_MAX 2048
static char          g_say[SAY_MAX];
static volatile LONG g_say_pending = 0;
static int           g_say_retry   = 0;

static int __cdecl nse_say(lua_State* L) {
    const char* s = L_.tolstring(L, 1, NULL);
    if (!s) { push_str(L, "NSE_Say: expected a string"); return 1; }
    if (g_say_pending) { push_str(L, "busy"); return 1; }   /* one at a time */
    _snprintf(g_say, SAY_MAX - 1, "%s", s);
    g_say[SAY_MAX - 1] = 0;
    g_say_pending = 1;
    push_str(L, "queued");
    return 1;
}

static void say_pump(void) {
    /* Re-entrancy guard - NOT optional. This runs inside the lua_getfield hook
     * and then calls Lua itself, which calls lua_getfield, which re-enters
     * here. Without the guard a nested loadbuffer corrupts the outer one's
     * stack and every attempt fails to compile. */
    static volatile LONG busy = 0;
    if (!g_say_pending || !g_uiL) return;
    if (InterlockedCompareExchange(&busy, 1, 0) != 0) return;

    g_say_pending = 0;      /* clear BEFORE running: a failure must not retry
                             * on every single hook call */

    char esc[SAY_MAX * 2]; int w = 0;
    for (int i = 0; g_say[i] && w < (int)sizeof(esc) - 8; i++) {
        char c = g_say[i];
        if (c == '\\' || c == '\'') { esc[w++] = '\\'; esc[w++] = c; }
        else if (c == '\n') { esc[w++] = '\\'; esc[w++] = 'n'; }
        else if (c == '\r') { }
        else esc[w++] = c;
    }
    esc[w] = 0;

    /* DEFER if a panel is already up. The game's own turn-start messages use
     * the SAME dialogue_box panel, so opening ours on top either loses our text
     * or interrupts theirs. Ask panelmanager first and retry later. */
    char chunk[SAY_MAX * 2 + 768];
    _snprintf(chunk, sizeof(chunk) - 1,
        "local pm "
        "for _,m in ipairs({'Utilities','CoreUtils'}) do "
        "  local ok,u = pcall(require, m) "
        "  if ok and type(u)=='table' and u.Require then "
        "    local ok2,p = pcall(u.Require, 'panelmanager') "
        "    if not (ok2 and type(p)=='table') then ok2,p = pcall(u.Require,'PanelManager') end "
        "    if ok2 and type(p)=='table' then pm = p break end "
        "  end "
        "end "
        "if type(pm)~='table' or not pm.OpenPanel then return 'nopm' end "
        "local busy = false "
        "for _,p in ipairs({'dialogue_box','event_message','message_scroll'}) do "
        "  local o,r = pcall(pm.IsPanelOpen, p) if o and r then busy = true end end "
        "if busy then return 'busy' end "
        "pcall(pm.OpenPanel,'dialogue_box',false,'Initialise','%s') return 'shown'",
        esc);
    chunk[sizeof(chunk) - 1] = 0;

    lua_State* L = g_uiL;
    int top = L_.gettop(L);
    if (L_.loadbuffer(L, chunk, strlen(chunk), "=nse_say") == 0) {
        if (L_.pcall(L, 0, 1, 0) == 0) {
            const char* r = L_.tolstring(L, -1, NULL);
            if (r && r[0] == 'b') {                 /* "busy" - screen occupied */
                if (++g_say_retry < 600) g_say_pending = 1;
                else nse_log("[nse] NSE_Say gave up after %d retries", g_say_retry);
            } else {
                if (r && r[0] == 'n') nse_log("[nse] NSE_Say: panelmanager not reachable from this state");
                g_say_retry = 0;
            }
        } else {
            const char* e = L_.tolstring(L, -1, NULL);
            nse_log("[nse] NSE_Say failed: %s", e ? e : "?");
        }
    } else {
        /* Log the ACTUAL compiler error and the chunk. "compile failed" with no
         * detail is the same fail-quietly trap this engine keeps setting. */
        const char* e = L_.tolstring(L, -1, NULL);
        nse_log("[nse] NSE_Say compile failed: %s", e ? e : "?");
        nse_log("[nse]   chunk was: %.300s", chunk);
    }
    L_.settop(L, top);
    InterlockedExchange(&busy, 0);
}

