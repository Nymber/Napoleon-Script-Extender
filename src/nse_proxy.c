/* ============================================================================
 * nse_proxy.c - Napoleon Script Extender, proxy-DLL edition.
 *
 * Ships as dinput8.dll in the game root. Windows loads a DLL from the
 * application directory before the system one, so Napoleon loads US, we forward
 * the five real exports to the system dinput8.dll, and meanwhile we get native
 * code running INSIDE the process before main() - which means our hooks are in
 * place before Lua even initialises. No injector, no attach timing race.
 *
 * WHY dinput8: Napoleon.exe imports DINPUT8.dll (verified from its import
 * table: ADVAPI32, binkw32, COMDLG32, d3d9, d3dx9d_40, DINPUT8, DSOUND, ...),
 * it has only five exports, and it is not a protected KnownDLL, so the
 * app-directory override reliably works. tbb/binkw32/mss32 also sit in the game
 * root but have far larger (and C++-mangled) export surfaces.
 *
 * THE POINT: a named pipe that evaluates arbitrary Lua IN THE RUNNING GAME, on
 * the game's own thread, in whichever lua_State you name. Iterate without
 * restarting.
 *
 * ---------------------------------------------------------------------------
 * WHAT IS VERIFIED, AND HOW
 *
 *   Napoleon.exe is 32-bit (machine 0x014C), ImageBase 0x00400000, and
 *   statically links the SAME Lua 5.1 build as Empire: Total War. The ten C API
 *   addresses below were located by tools/find_lua_api.rb, which masks
 *   relocation-dependent bytes out of Empire's known function bodies and
 *   searches Napoleon's .text for the remainder. Each matched exactly once, AND
 *   all ten landed at identical relative offsets from lua_getfield - the same
 *   object file, relocated by 0xE1B70. Ten functions agreeing on ten offsets is
 *   the proof; a single unique hit would not have been.
 *
 *   Run `ruby tools/find_lua_api.rb --verify` to re-derive these. If a patch
 *   moves them, that is the tool that tells you the new values.
 *
 * WHAT IS *NOT* VERIFIED
 *
 *   Everything above was established statically, from the binary and the
 *   shipped packs. Nothing here has been run against a live Napoleon process.
 *   Treat the first launch as a bring-up: check nse_log.txt, expect the
 *   prologue guard to refuse rather than to corrupt, and read the "bring-up"
 *   section of the README before assuming a silent failure is a crash.
 *
 *   The battle-state binding in particular is a heuristic (see g_battleL). If
 *   it never fires, `@battle` reports that plainly instead of guessing.
 * ========================================================================= */

