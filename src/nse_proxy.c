/* ---- pipe <-> game-thread handoff.
 * The pipe thread NEVER touches Lua. It fills g_req, raises g_pending and
 * waits; the pump, running on the game thread inside a Lua hook, executes it
 * and raises g_done. This is the single most important safety property here:
 * lua_State is not thread-safe, and the engine's allocator and GC assume
 * single-threaded access. */
#define REQ_MAX 8192
#define RES_MAX 8192
static volatile LONG g_pending = 0;
static volatile LONG g_done    = 0;
static char g_req[REQ_MAX];
static char g_res[RES_MAX];

/* Where the log goes. Resolved once, on first use.
 *
 * The default Steam library lives under Program Files (x86), which is NOT
 * user-writable. There, fopen("nse_log.txt","a") fails and the extender would
 * run perfectly while producing no log at all - and the documented diagnosis
 * ("no log means the DLL never loaded") would be exactly wrong, sending people
 * to debug a problem they do not have.
 *
 * So: try the game folder, and fall back to the game's own settings directory
 * under %APPDATA%, which Napoleon already writes to and which is always
 * writable for the user running it. */
static char  g_logpath[MAX_PATH] = {0};
static LONG  g_logpath_done = 0;

static void resolve_logpath(void) {
    if (InterlockedCompareExchange(&g_logpath_done, 1, 0) != 0) return;

    /* first choice: beside the game, where people expect to find it */
    FILE* probe = fopen("nse_log.txt", "a");
    if (probe) {
        fclose(probe);
        strcpy(g_logpath, "nse_log.txt");
        return;
    }

    /* fallback: %APPDATA%\The Creative Assembly\Napoleon\nse_log.txt
     * The directory already exists on any machine that has run the game once;
     * create it anyway in case this is a first launch. */
    const char* appdata = getenv("APPDATA");
    if (appdata) {
        char dir[MAX_PATH];
        _snprintf(dir, MAX_PATH - 1, "%s\\The Creative Assembly", appdata);
        dir[MAX_PATH - 1] = 0; CreateDirectoryA(dir, NULL);
        _snprintf(dir, MAX_PATH - 1, "%s\\The Creative Assembly\\Napoleon", appdata);
        dir[MAX_PATH - 1] = 0; CreateDirectoryA(dir, NULL);
        _snprintf(g_logpath, MAX_PATH - 1, "%s\\nse_log.txt", dir);
        g_logpath[MAX_PATH - 1] = 0;
        FILE* f = fopen(g_logpath, "a");
        if (f) { fclose(f); return; }
    }
    /* Nowhere to write. Leave the path empty; logging becomes a no-op rather
     * than a crash, and the pipe still answers "@nat states". */
    g_logpath[0] = 0;
}

static void nse_log(const char* fmt, ...) {
    char buf[1024];
    va_list ap; va_start(ap, fmt);
    _vsnprintf(buf, sizeof(buf)-1, fmt, ap); buf[sizeof(buf)-1] = 0;
    va_end(ap);
    resolve_logpath();
    if (!g_logpath[0]) return;
    /* Opened and closed per line on purpose: anything logged is on disk before
     * the next statement runs, which is the only reliable way to get data out
     * of a session that is about to die. */
    FILE* f = fopen(g_logpath, "a");
    if (f) { fprintf(f, "%s\n", buf); fclose(f); }
}

/* ======================= trampoline construction ========================= *
 * Built as raw bytes at runtime rather than as a naked function: no inline-asm
 * syntax or symbol-decoration surprises, and total control over the layout.
 *
 *   9C                    pushfd
 *   60                    pushad
 *   8D 44 24 24           lea eax,[esp+0x24]   ; -> original stack frame
 *   50                    push eax             ; handler(stk)
 *   B8 <handler>          mov eax,<handler>
 *   FF D0                 call eax
 *   83 C4 04              add esp,4
 *   61                    popad
 *   9D                    popfd
 *   <stolen bytes>
 *   68 <ret>              push <site+steal>    ; push/ret avoids computing a
 *   C3                    ret                  ; relative displacement
 *
 * After pushfd(4)+pushad(0x20)=0x24, [esp+0x24] is the original [esp+0], so the
 * handler receives {retaddr, arg1, arg2, arg3, ...}.
 * ========================================================================= */
static void* make_tramp(unsigned char* site, void* handler, int stealLen) {
    unsigned char* t = (unsigned char*)VirtualAlloc(NULL, 64,
                            MEM_COMMIT|MEM_RESERVE, PAGE_EXECUTE_READWRITE);
    if (!t) return NULL;
    int i = 0;
    t[i++] = 0x9C;
    t[i++] = 0x60;
    t[i++] = 0x8D; t[i++] = 0x44; t[i++] = 0x24; t[i++] = 0x24;
    t[i++] = 0x50;
    t[i++] = 0xB8; *(void**)(t+i) = handler;         i += 4;
    t[i++] = 0xFF; t[i++] = 0xD0;
    t[i++] = 0x83; t[i++] = 0xC4; t[i++] = 0x04;
    t[i++] = 0x61;
    t[i++] = 0x9D;
    memcpy(t+i, site, stealLen);                     i += stealLen;
    t[i++] = 0x68; *(void**)(t+i) = (void*)(site + stealLen); i += 4;
    t[i++] = 0xC3;
    return t;
}

/* Patch `site` with E9 rel32 -> tramp. The prologue is verified FIRST and the
 * hook refused on a mismatch. This is what turns "a patch moved the function"
 * from silent memory corruption into a line in the log. It is not optional. */
static int install_hook_ex(DWORD staticAddr, void* handler,
                           const unsigned char* expect, int stealLen) {
    unsigned char* site = (unsigned char*)(staticAddr + g_delta);
    if (memcmp(site, expect, stealLen) != 0) {
        nse_log("[nse] REFUSING to hook %p: prologue mismatch (%02X %02X %02X %02X %02X)",
                site, site[0], site[1], site[2], site[3], site[4]);
        nse_log("[nse]   expected %02X %02X %02X %02X %02X",
                expect[0], expect[1], expect[2], expect[3], expect[4]);
        nse_log("[nse]   These addresses were derived for %s.", NSE_TARGET_DESC);
        nse_log("[nse]   Recover with: ruby tools/find_lua_api.rb --verify");
        return 0;
    }
    void* tramp = make_tramp(site, handler, stealLen);
    if (!tramp) { nse_log("[nse] trampoline alloc failed"); return 0; }

    DWORD old;
    if (!VirtualProtect(site, stealLen, PAGE_EXECUTE_READWRITE, &old)) return 0;
    site[0] = 0xE9;
    *(DWORD*)(site+1) = (DWORD)tramp - ((DWORD)site + 5);
    VirtualProtect(site, stealLen, old, &old);
    FlushInstructionCache(GetCurrentProcess(), site, stealLen);
    nse_log("[nse] hooked %p -> tramp %p (steal %d)", site, tramp, stealLen);
    return 1;
}

static int install_hook(DWORD a, void* h) { return install_hook_ex(a, h, kProlog, STEAL); }

